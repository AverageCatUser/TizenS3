static int cmd(uint8_t c)
{
	uint8_t b[2] = { 0x00, c };          /* Co=0, D/C#=0 : command */
	return s3_i2c_write(g_addr, b, 2);
}

int s3_ssd1306_init(int scl, int sda, uint8_t addr, int width, int height)
{
	int ret;
	static const uint8_t seq[] = {
		0xae, 0xd5, 0x80, 0xa8, 0x3f, 0xd3, 0x00, 0x40,
		0x8d, 0x14, 0x20, 0x00, 0xa1, 0xc8, 0xda, 0x12,
		0x81, 0x7f, 0xd9, 0xf1, 0xdb, 0x40, 0xa4, 0xa6, 0xaf
	};

	if (addr) {
		g_addr = addr;
	}
	/* the framebuffer is sized for 128x64; anything else would overflow it */
	g_w = 128;
	g_h = (height == 32) ? 32 : 64;
	(void)width;

	ret = s3_i2c_init(scl, sda, 400);
	if (ret < 0) {
		return ret;
	}

	for (unsigned i = 0; i < sizeof(seq); i++) {
		/* MUX for 128x32 panels */
		uint8_t c = seq[i];
		if (seq[i] == 0x3f && g_h == 32) {
			c = 0x1f;
		}
		if (seq[i] == 0x12 && g_h == 32) {
			c = 0x02;
		}
		ret = cmd(c);
		if (ret < 0) {
			return ret;             /* no panel / wrong address */
		}
	}

	s3_ssd1306_clear();
	return s3_ssd1306_show();
}

void s3_ssd1306_clear(void)
{
	memset(g_fb, 0, (size_t)g_w * g_h / 8);
}

void s3_ssd1306_pixel(int x, int y, int on)
{
	if (x < 0 || x >= g_w || y < 0 || y >= g_h) {
		return;
	}
	uint8_t *p = &g_fb[x + (y / 8) * g_w];
	if (on) {
		*p |= (1u << (y & 7));
	} else {
		*p &= ~(1u << (y & 7));
	}
}

void s3_ssd1306_char(int x, int y, char ch)
{
	if (ch < 0x20 || ch > 0x7e) {
		ch = '?';
	}
	const uint8_t *g = font5x7[ch - 0x20];
	for (int col = 0; col < 5; col++) {
		for (int row = 0; row < 7; row++) {
			s3_ssd1306_pixel(x + col, y + row, (g[col] >> row) & 1);
		}
	}
}

void s3_ssd1306_text(int x, int y, const char *s)
{
	while (*s) {
		if (*s == '\n') {
			y += 8;
			x = 0;
		} else {
			s3_ssd1306_char(x, y, *s);
			x += 6;
			if (x > g_w - 5) {
				x = 0;
				y += 8;
			}
		}
		s++;
	}
}

int s3_ssd1306_show(void)
{
	int ret;
	int pages = g_h / 8;

	for (int page = 0; page < pages; page++) {
		if ((ret = cmd(0xb0 + page)) < 0) return ret;     /* page */
		if ((ret = cmd(0x00)) < 0) return ret;            /* low col */
		if ((ret = cmd(0x10)) < 0) return ret;            /* high col */

		/* one row of data, 17 bytes at a time (control byte + 16) */
		uint8_t buf[17];
		uint8_t *src = &g_fb[page * g_w];
		int sent = 0;
		while (sent < g_w) {
			int n = (g_w - sent > 16) ? 16 : (g_w - sent);
			buf[0] = 0x40;                               /* D/C#=1 : data */
			memcpy(&buf[1], src + sent, n);
			if ((ret = s3_i2c_write(g_addr, buf, n + 1)) < 0) return ret;
			sent += n;
		}
	}
	return 0;
}
